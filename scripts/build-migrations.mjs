import fs from "node:fs";
import path from "node:path";
const directory = "supabase/migrations";
const names = fs
  .readdirSync(directory)
  .filter((name) => /^\d+_.+\.sql$/.test(name))
  .sort();
let bundle = `-- Generated from versioned migrations by npm run db:sql. Do not edit this file.\n-- Run once in your hosted Supabase SQL Editor as the project owner. No database URL is needed.\n-- Already-applied versions are skipped, using the Supabase CLI's migration history.\nbegin;\nselect pg_advisory_xact_lock(hashtextextended('product-schema-migrations',0));\ncreate schema if not exists supabase_migrations;\ncreate table if not exists supabase_migrations.schema_migrations(version text primary key, statements text[], name text);\n`;
for (const name of names) {
  const [version, ...parts] = name.replace(/\.sql$/, "").split("_");
  const migration = fs.readFileSync(path.join(directory, name), "utf8");
  const tag = `$migration_${version}$`;
  const bodyTag = `$source_${version}$`;
  if (migration.includes(tag) || migration.includes(bodyTag))
    throw new Error("Migration delimiter collision");
  bundle += `\ndo ${tag}\nbegin\n if not exists(select 1 from supabase_migrations.schema_migrations where version='${version}') then\n${migration}\n insert into supabase_migrations.schema_migrations(version,name,statements) values('${version}','${parts.join("_")}',array[${bodyTag}${migration}${bodyTag}]);\n end if;\nend;\n${tag};\n`;
}
bundle += "\ncommit;\nnotify pgrst,'reload schema';\n";
fs.writeFileSync("supabase/setup.sql", bundle);
console.log(
  `Built supabase/setup.sql from ${names.length} versioned migrations. Paste it into Supabase SQL Editor and run once.`,
);
